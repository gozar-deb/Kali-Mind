"""HTML report generator with dark cybersecurity aesthetic."""
from __future__ import annotations

from datetime import datetime
from typing import List

from kali_mind import __version__
from kali_mind.evidence.store import EvidenceRecord, Finding, Session

_SEVERITY_COLORS = {
    "critical": "#ff2d2d",
    "high": "#ff6b35",
    "medium": "#ffd700",
    "low": "#4fc3f7",
    "informational": "#aaaaaa",
}

_HTML_TEMPLATE = """\
<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<title>Kali-Mind Security Report — {session_name}</title>
<style>
  :root {{
    --bg: #0d1117;
    --surface: #161b22;
    --surface2: #21262d;
    --border: #30363d;
    --text: #c9d1d9;
    --text-dim: #8b949e;
    --accent: #58a6ff;
    --green: #3fb950;
    --critical: #ff2d2d;
    --high: #ff6b35;
    --medium: #ffd700;
    --low: #4fc3f7;
    --info: #aaa;
  }}
  * {{ box-sizing: border-box; margin: 0; padding: 0; }}
  body {{ background: var(--bg); color: var(--text); font-family: 'Courier New', monospace; font-size: 14px; line-height: 1.6; padding: 2rem; }}
  h1 {{ color: var(--accent); font-size: 2rem; margin-bottom: 0.5rem; }}
  h2 {{ color: var(--accent); font-size: 1.4rem; border-bottom: 1px solid var(--border); padding-bottom: 0.5rem; margin: 2rem 0 1rem; }}
  h3 {{ color: var(--text); font-size: 1.1rem; margin: 1.5rem 0 0.5rem; }}
  .header {{ border: 1px solid var(--border); background: var(--surface); padding: 1.5rem; border-radius: 8px; margin-bottom: 2rem; }}
  .header .meta {{ color: var(--text-dim); font-size: 0.85rem; margin-top: 0.5rem; }}
  .summary-grid {{ display: grid; grid-template-columns: repeat(auto-fill, minmax(140px, 1fr)); gap: 1rem; margin: 1rem 0; }}
  .sev-card {{ padding: 1rem; border-radius: 6px; border: 1px solid; text-align: center; }}
  .sev-card .count {{ font-size: 2rem; font-weight: bold; }}
  .sev-card .label {{ font-size: 0.8rem; color: var(--text-dim); text-transform: uppercase; }}
  .finding {{ background: var(--surface); border: 1px solid var(--border); border-radius: 6px; padding: 1.5rem; margin-bottom: 1.5rem; border-left: 4px solid; }}
  .badge {{ display: inline-block; padding: 2px 8px; border-radius: 4px; font-size: 0.75rem; font-weight: bold; text-transform: uppercase; }}
  .meta-table {{ width: 100%; border-collapse: collapse; margin: 1rem 0; }}
  .meta-table td {{ padding: 0.4rem 0.8rem; border: 1px solid var(--border); }}
  .meta-table td:first-child {{ color: var(--text-dim); width: 160px; }}
  code, pre {{ background: var(--surface2); padding: 0.2rem 0.5rem; border-radius: 4px; font-family: 'Courier New', monospace; }}
  pre {{ padding: 1rem; overflow-x: auto; margin: 0.5rem 0; }}
  table.cmd {{ width: 100%; border-collapse: collapse; font-size: 0.85rem; }}
  table.cmd th {{ background: var(--surface2); color: var(--text-dim); padding: 0.5rem; text-align: left; border: 1px solid var(--border); }}
  table.cmd td {{ padding: 0.4rem 0.5rem; border: 1px solid var(--border); }}
  .footer {{ margin-top: 3rem; color: var(--text-dim); font-size: 0.8rem; text-align: center; }}
</style>
</head>
<body>
<div class="header">
  <h1>⚔ KALI-MIND Security Report</h1>
  <div class="meta">
    Session: <strong>{session_name}</strong> ({session_id}) &nbsp;|&nbsp;
    Generated: <strong>{generated}</strong> &nbsp;|&nbsp;
    Status: <strong>{status}</strong>
  </div>
</div>

<h2>Executive Summary</h2>
<div class="summary-grid">
{summary_cards}
</div>

<h2>Findings</h2>
{findings_html}

<h2>Command History</h2>
<table class="cmd">
  <tr><th>#</th><th>Tool</th><th>Operation</th><th>Target</th><th>Exit</th></tr>
  {command_rows}
</table>

<div class="footer">Generated by Kali-Mind v{__version__} &mdash; {generated}</div>
</body>
</html>
"""


def generate_html(
    session: Session,
    evidence: List[EvidenceRecord],
    findings: List[Finding],
) -> str:
    now = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    severity_order = {"critical": 0, "high": 1, "medium": 2, "low": 3, "informational": 4}
    findings_sorted = sorted(findings, key=lambda f: severity_order.get(f.severity, 5))
    counts = {s: len([f for f in findings if f.severity == s]) for s in severity_order}

    # Summary cards
    cards = []
    for sev, count in counts.items():
        color = _SEVERITY_COLORS.get(sev, "#aaa")
        cards.append(
            f'<div class="sev-card" style="border-color:{color};color:{color}">'
            f'<div class="count">{count}</div>'
            f'<div class="label">{sev}</div>'
            f"</div>"
        )
    summary_cards = "\n".join(cards)

    # Findings HTML
    findings_parts = []
    if not findings_sorted:
        findings_parts.append("<p>No findings recorded for this session.</p>")
    for i, f in enumerate(findings_sorted, 1):
        color = _SEVERITY_COLORS.get(f.severity, "#aaa")
        src = "OBSERVED" if f.is_observed else "AI INFERENCE"
        ev_html = f"<pre>{_esc(f.evidence)}</pre>" if f.evidence else ""
        impact_html = f"<p><strong>Impact:</strong> {_esc(f.potential_impact)}</p>" if f.potential_impact else ""
        rem_html = f"<p><strong>Remediation:</strong> {_esc(f.remediation)}</p>" if f.remediation else ""
        findings_parts.append(f"""
<div class="finding" style="border-left-color:{color}">
  <h3>#{i:03d} — {_esc(f.title)}</h3>
  <table class="meta-table">
    <tr><td>Severity</td><td><span class="badge" style="background:{color};color:#000">{_esc(f.severity.upper())}</span></td></tr>
    <tr><td>Confidence</td><td>{_esc(f.confidence.capitalize())}</td></tr>
    <tr><td>Affected Asset</td><td><code>{_esc(f.affected_asset)}</code></td></tr>
    <tr><td>Source</td><td>{src}</td></tr>
    <tr><td>Detected By</td><td>{_esc(f.detection_source)}</td></tr>
    <tr><td>Timestamp</td><td>{_esc(f.timestamp)}</td></tr>
  </table>
  <p>{_esc(f.description)}</p>
  {ev_html}{impact_html}{rem_html}
</div>""")
    findings_html = "\n".join(findings_parts)

    # Command rows
    cmd_rows = []
    for i, ev in enumerate(evidence, 1):
        cmd_rows.append(
            f"<tr><td>{i}</td><td>{_esc(ev.tool)}</td><td>{_esc(ev.operation)}</td>"
            f"<td><code>{_esc(ev.target)}</code></td><td>{ev.exit_code}</td></tr>"
        )
    command_rows = "\n".join(cmd_rows) or "<tr><td colspan='5'>No commands recorded</td></tr>"

    return _HTML_TEMPLATE.format(
        session_name=_esc(session.name),
        session_id=_esc(session.id),
        generated=now,
        status=_esc(session.status),
        summary_cards=summary_cards,
        findings_html=findings_html,
        command_rows=command_rows,
        __version__=__version__,
    )


def _esc(text: str) -> str:
    return (
        str(text)
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )

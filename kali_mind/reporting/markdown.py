"""Markdown report generator."""
from __future__ import annotations

from datetime import datetime
from typing import List

from kali_mind import __version__
from kali_mind.evidence.store import EvidenceRecord, Finding, Session


def generate_markdown(
    session: Session,
    evidence: List[EvidenceRecord],
    findings: List[Finding],
) -> str:
    now = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    severity_order = {"critical": 0, "high": 1, "medium": 2, "low": 3, "informational": 4}
    findings_sorted = sorted(findings, key=lambda f: severity_order.get(f.severity, 5))

    counts = {s: len([f for f in findings if f.severity == s]) for s in severity_order}

    lines = [
        f"# Security Assessment Report",
        f"",
        f"**Session:** {session.name} (`{session.id}`)",
        f"**Date:** {now}",
        f"**Status:** {session.status}",
        f"",
        f"---",
        f"",
        f"## Executive Summary",
        f"",
        f"This report presents the findings from a security assessment conducted using Kali-Mind.",
        f"All testing was performed against authorized targets within the defined scope.",
        f"",
        f"| Severity      | Count |",
        f"|---------------|-------|",
    ]
    for sev, count in counts.items():
        lines.append(f"| {sev.capitalize():<13} | {count:<5} |")

    lines += [
        f"",
        f"---",
        f"",
        f"## Scope",
        f"",
    ]
    if session.scope:
        for k, v in session.scope.items():
            if isinstance(v, list):
                lines.append(f"**{k}:**")
                for item in v:
                    lines.append(f"  - {item}")
            else:
                lines.append(f"**{k}:** {v}")
    else:
        lines.append("_No scope information recorded._")

    lines += [
        f"",
        f"---",
        f"",
        f"## Findings",
        f"",
    ]

    if not findings_sorted:
        lines.append("_No findings recorded for this session._")
    else:
        for i, f in enumerate(findings_sorted, 1):
            src = "OBSERVED" if f.is_observed else "AI INFERENCE"
            lines += [
                f"### Finding #{i:03d} — {f.title}",
                f"",
                f"| Field             | Value |",
                f"|-------------------|-------|",
                f"| **Severity**      | {f.severity.upper()} |",
                f"| **Confidence**    | {f.confidence.capitalize()} |",
                f"| **Asset**         | `{f.affected_asset}` |",
                f"| **Source**        | {src} |",
                f"| **Detected**      | {f.detection_source} |",
                f"| **Timestamp**     | {f.timestamp} |",
                f"",
                f"**Description:**",
                f"{f.description}",
                f"",
            ]
            if f.evidence:
                lines += [f"**Evidence:**", f"```", f.evidence, f"```", f""]
            if f.potential_impact:
                lines += [f"**Potential Impact:**", f"{f.potential_impact}", f""]
            if f.remediation:
                lines += [f"**Remediation:**", f"{f.remediation}", f""]
            if f.references:
                lines.append("**References:**")
                for ref in f.references:
                    lines.append(f"  - {ref}")
                lines.append("")
            lines.append("---")
            lines.append("")

    # Command history
    lines += [
        f"## Command History",
        f"",
        f"| # | Tool | Operation | Target | Exit | Duration |",
        f"|---|------|-----------|--------|------|----------|",
    ]
    for i, ev in enumerate(evidence, 1):
        lines.append(
            f"| {i} | {ev.tool} | {ev.operation} | `{ev.target}` | {ev.exit_code} | — |"
        )

    lines += [
        f"",
        f"---",
        f"",
        f"*Generated by Kali-Mind v{__version__} — {now}*",
        f"",
    ]

    return "\n".join(lines)
